function toRows(modules: boolean[][]): string[] {
  return modules.map((row) => row.map((module) => (module ? '1' : '0')).join(''))
}

describe('encodeQrCode', () => {
  for (const reference of REFERENCES) {
    it(`matches the reference symbol for ${reference.label}`, () => {
      const code = encodeQrCode(reference.text)

      expect(code.size).toBe(reference.rows.length)
      expect(toRows(code.modules)).toEqual(reference.rows)
    })
  }

  it('grows the version with the payload and keeps the symbol square', () => {
    const small = encodeQrCode('a')
    const large = encodeQrCode('z'.repeat(200))

    expect(small.version).toBe(1)
    expect(small.size).toBe(21)
    expect(large.version).toBe(10)
    expect(large.size).toBe(57)
    expect(large.modules.every((row) => row.length === large.size)).toBe(true)
  })

  it('always emits the three finder patterns', () => {
    const { modules, size } = encodeQrCode('http://192.168.1.10:8479/?t=abc123')
    const corners: Array<[number, number]> = [
      [0, 0],
      [0, size - 7],
      [size - 7, 0]
    ]

    for (const [row, column] of corners) {
      expect(modules[row][column]).toBe(true)
      expect(modules[row + 1][column + 1]).toBe(false)
      expect(modules[row + 3][column + 3]).toBe(true)
    }
  })

  it('rejects payloads that do not fit a version 10 symbol', () => {
    expect(() => encodeQrCode('x'.repeat(400))).toThrow(/too long/i)
  })
})

describe('renderQrCodeSvg', () => {
  it('renders a self-contained svg sized to the symbol plus its quiet zone', () => {
    const url = 'http://192.168.1.10:8479/?t=sekrittoken'
    const svg = renderQrCodeSvg(url, { margin: 2 })
    const code = encodeQrCode(url)

    expect(svg.startsWith('<svg')).toBe(true)
    expect(svg.endsWith('</svg>')).toBe(true)
    expect(svg).toContain(`viewBox="0 0 ${code.size + 4} ${code.size + 4}"`)
    // The payload only exists as modules, never as readable text in the markup.
    expect(svg).not.toContain('sekrittoken')
  })
})
